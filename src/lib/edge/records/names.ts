/** The listed parent for a filed name, or null. Pure. */
export function tickerFor(rules: NameRule[], filed: string): NameRule | null {
  const name = filed.replace(/\s+/g, " ").trim();
  if (!name) return null;
  return rules.find((r) => r.re.test(name)) ?? null;
}
